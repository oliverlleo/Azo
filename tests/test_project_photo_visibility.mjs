import assert from 'node:assert/strict';
import {projectPhotoPath,photoRecordId,visibleProjectPhotos,hiddenProjectPhotos} from '../assets/js/project-photo-visibility.mjs';
const first='assets/images/projects/as-1.webp';
const second='assets/images/projects/as-2.webp';
assert.equal(projectPhotoPath('/assets/images/projects/as-1-sm.webp'),first);
assert.equal(photoRecordId(first),photoRecordId('assets/images/projects/as-1-sm.webp'));
assert.equal(projectPhotoPath('assets/images/logo-azo.png'),'');
assert.equal(projectPhotoPath('assets/images/projects/zz-1.webp'),'');
const hidden=hiddenProjectPhotos([{id:photoRecordId(first),items:[{key:first,type:'project-photo-visibility',value:true}]}]);
assert.equal(visibleProjectPhotos('AS',hidden).length,5);
assert.equal(visibleProjectPhotos('AS',hidden)[0],second);
assert.equal(visibleProjectPhotos('HL',hidden).length,6);
assert.deepEqual(visibleProjectPhotos('AS',new Set(visibleProjectPhotos('AS',new Set()))),[]);
assert.equal(hiddenProjectPhotos([{id:photoRecordId(first),items:[{key:first,type:'project-photo-visibility',value:false}]}]).size,0);
assert.equal(hiddenProjectPhotos([{id:photoRecordId(second),items:[{key:first,type:'project-photo-visibility',value:true}]}]).size,0);
console.log('Project photo visibility tests passed.');
